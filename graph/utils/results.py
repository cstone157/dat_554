
def _generate_results_printout(result: dict) -> str:
    """
    Generate a formatted string containing the results of the agent's execution.
    This includes the user description, implementation plan, generated code,
    execution results, and evaluation.
    Args:
        result (dict): A dictionary containing the results of the agent's execution.
            Expected keys include:
                - 'user_description': The description provided by the user.
                - 'plan': The implementation plan generated by the agent.
                - 'generated_code': The code generated by the agent.
                - 'execution_result': A dictionary containing execution results with keys:
                    - 'stdout': Standard output from code execution.
                    - 'stderr': Standard error from code execution.
                    - 'returncode': Return code from code execution.
                - 'evaluation': Evaluation of the generated code and its execution.
                - 'pending_tasks': List of pending tasks (optional).
                - 'completed_tasks': List of completed tasks (optional).
    Returns:
        str: A formatted string summarizing the results.
    """
    # Build and display results
    lines = []
    lines.append("\n" + "=" * 60)
    lines.append("  RESULTS")
    lines.append("=" * 60)
    lines.append("\n📝 User Description:")
    lines.append(f"   {result['user_description']}")
    lines.append("\n�️  Implementation Plan:")
    lines.append("-" * 40)
    lines.append(result.get("plan", "No plan generated."))
    lines.append("-" * 40)    
    pending = result.get("pending_tasks", [])
    completed = result.get("completed_tasks", [])
    if pending or completed:
        lines.append("\n✅ Tasks:")
        if pending:
            lines.append("   Pending:")
            for task in pending:
                lines.append(f"      [{task.get('id', '?')}] {task.get('title', 'Untitled')}")
        if completed:
            lines.append("   Completed:")
            for task in completed:
                lines.append(f"      [{task.get('id', '?')}] {task.get('title', 'Untitled')}")
        lines.append("-" * 40)    
    lines.append("\n�💻 Generated Code:")
    lines.append("-" * 40)
    lines.append(result["generated_code"])
    lines.append("-" * 40)

    exec_result = result["execution_result"]
    lines.append("\n⚡ Execution Results:")
    if exec_result["stdout"]:
        lines.append(f"\n   Standard Output:\n   {exec_result['stdout']}")
    if exec_result["stderr"]:
        lines.append(f"\n   Standard Error:\n   {exec_result['stderr']}")
    lines.append(f"   Return Code: {exec_result['returncode']}")

    lines.append("\n📊 Evaluation:")
    lines.append("-" * 40)
    lines.append(result["evaluation"])
    lines.append("-" * 40)
    output_text = "\n".join(lines) + "\n"

    # Run the workflow
    print("=" * 60)
    print("  Python Code Generator & Evaluator")
    print("=" * 60)
    print()

    # Print to console
    print(output_text)
    return output_text